using System.Diagnostics;

if (args.Length == 2 && args[0] == "--stamp-identity")
{
    StampExistingIdentity(Path.GetFullPath(args[1]));
    return;
}
if (args.Length is not (0 or 1 or 3 or 5)) throw new ArgumentException("output-directory [--max-kernels 1..17] [--timeout-seconds 1..180] or --stamp-identity <existing-artifacts>");
var maximumKernels = 17;
var timeoutSeconds = 180;
if (args.Length >= 3 && (args[1] != "--max-kernels" || !int.TryParse(args[2], out maximumKernels) || maximumKernels is < 1 or > 17))
    throw new ArgumentException("--max-kernels must be 1..17.");
if (args.Length == 5 && (args[3] != "--timeout-seconds" || !int.TryParse(args[4], out timeoutSeconds) || timeoutSeconds is < 1 or > 180))
    throw new ArgumentException("--timeout-seconds must be 1..180.");
using var deadline = new CancellationTokenSource(TimeSpan.FromSeconds(timeoutSeconds));
Console.CancelKeyPress += (_, eventArgs) => { eventArgs.Cancel = true; deadline.Cancel(); };
var clock = Stopwatch.StartNew();
void Check() { deadline.Token.ThrowIfCancellationRequested(); if (clock.Elapsed.TotalSeconds >= timeoutSeconds) throw new TimeoutException("Kernel compilation deadline."); }
Check();

using var context = Context.Create(builder => builder.EnableAlgorithms().Math(MathMode.Default));
using var backend = new PTXBackend(context, new CudaArchitecture(7, 0), new CudaInstructionSet(7, 0), null!);

var outputDirectory = args.Length == 0 ? Path.Combine("artifacts", "kernels") : Path.GetFullPath(args[0]);
Directory.CreateDirectory(outputDirectory);
var names = new[]
{
    nameof(TransformerKernels.VectorAdd), nameof(TransformerKernels.Linear), nameof(TransformerKernels.Embedding),
    nameof(TransformerKernels.Norm), nameof(TransformerKernels.SplitQkv), nameof(TransformerKernels.Rope),
    nameof(TransformerKernels.AttentionScores), nameof(TransformerKernels.Softmax), nameof(TransformerKernels.AttentionContext),
    nameof(TransformerKernels.Add), nameof(TransformerKernels.Activate), nameof(TransformerKernels.GatedGelu),
    nameof(TransformerKernels.RowBias), nameof(TransformerKernels.TypeEmbeddingAdd),
    nameof(TransformerKernels.MarkerCrossEntropy), nameof(TransformerKernels.MarkerGradientSgd), nameof(TransformerKernels.MarkerUpdateStatus),
};
var records = new List<KernelRecord>(names.Length);
var source = new StringBuilder("// Generated by Sezika.KernelCompiler; do not edit.\nnamespace Sezika.Cuda;\n\ninternal static class GeneratedKernelArtifacts\n{\n    internal readonly record struct Descriptor(string Entry, int ParameterCount, int BlockSize);\n");
var sourcePath = Path.Combine("src", "Sezika.Kernels", "TransformerKernels.cs");
var sourceHash = File.Exists(sourcePath) ? Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(sourcePath))) : throw new FileNotFoundException("C# kernel source is missing.", sourcePath);
source.Append("    internal const string CompilerVersion = \"ILGPU 1.5.3\";\n    internal const string SourceSha256 = \"").Append(sourceHash).Append("\";\n");
// At most seventeen kernels, bounded PTX bytes/ABI lines, cancellation and wall time.
foreach (var name in names.Take(maximumKernels))
{
    Check();
    var method = typeof(TransformerKernels).GetMethod(name, BindingFlags.Public | BindingFlags.Static)!;
    var description = EntryPointDescription.FromExplicitlyGroupedKernel(method);
    var kernel = (PTXCompiledKernel)backend.Compile(description, KernelSpecialization.Empty);
    Check();
    var ptx = kernel.PTXAssembly.Replace("\r\n", "\n", StringComparison.Ordinal).Replace('\r', '\n').TrimEnd() + "\0";
    if (ptx.Length > 1_048_576) throw new InvalidDataException("PTX exceeds one MiB per kernel.");
    var entry = Regex.Match(ptx, @"\.visible \.entry\s+(?<name>[A-Za-z0-9_]+)\s*\(").Groups["name"].Value;
    if (string.IsNullOrWhiteSpace(entry)) throw new InvalidOperationException($"No PTX entry found for {name}.");
    var abi = ParseAbi(ptx, method, Check);
    var file = name + ".ptx";
    var ptxBytes = Encoding.ASCII.GetBytes(ptx);
    File.WriteAllBytes(Path.Combine(outputDirectory, file), ptxBytes);
    source.Append("    internal static ReadOnlySpan<byte> ").Append(name).Append(" => new byte[] { ");
    for (var index = 0; index < ptxBytes.Length && index < 1_048_576; index++)
    {
        if ((index & 255) == 0) Check();
        source.Append("0x").Append(ptxBytes[index].ToString("X2")).Append(", ");
    }
    source.Append("};\n");
    source.Append("    internal static Descriptor ").Append(name).Append("Descriptor => new(\"").Append(entry).Append("\", ").Append(abi.Length).Append(", 256);\n");
    records.Add(new KernelRecord(name, entry, file, Convert.ToHexString(SHA256.HashData(ptxBytes)), 256, abi));
    Console.WriteLine($"Compiled kernel {records.Count}/{maximumKernels}: {name}");
}
Check();
// Use a BOM-free encoding so generated artifacts are byte-for-byte reproducible
// across the Windows and Linux build tools. The manifest and checked-in source
// are hashed as bytes, so an implicit UTF-8 BOM would invalidate the manifest.
var utf8NoBom = new UTF8Encoding(encoderShouldEmitUTF8Identifier: false);
var manifest = new { schemaVersion = 1, compiler = "ILGPU", compilerVersion = "1.5.3", target = "sm_70", ptxVersion = "7.0", sourceSha256 = sourceHash, kernels = records };
var manifestJson = JsonSerializer.Serialize(manifest, new JsonSerializerOptions { WriteIndented = true, PropertyNamingPolicy = JsonNamingPolicy.CamelCase })
    .Replace("\r\n", "\n", StringComparison.Ordinal);
File.WriteAllText(Path.Combine(outputDirectory, "kernel-manifest.json"), manifestJson, utf8NoBom);
var manifestHash = Convert.ToHexString(SHA256.HashData(utf8NoBom.GetBytes(manifestJson)));
source.Append("    internal const string ManifestSha256 = \"").Append(manifestHash).Append("\";\n}\n");
File.WriteAllText(Path.Combine(outputDirectory, "GeneratedKernelArtifacts.g.cs"), source.ToString(), utf8NoBom);
Console.WriteLine($"Generated {records.Count} PTX kernels at {outputDirectory}.");

static void StampExistingIdentity(string directory)
{
    using var deadline = new CancellationTokenSource(TimeSpan.FromSeconds(20));
    ConsoleCancelEventHandler handler = (_, eventArgs) => { eventArgs.Cancel = true; deadline.Cancel(); };
    Console.CancelKeyPress += handler;
    var clock = Stopwatch.StartNew();
    void Check() { deadline.Token.ThrowIfCancellationRequested(); if (clock.Elapsed > TimeSpan.FromSeconds(20)) throw new TimeoutException("Existing artifact identity deadline."); }
    try
    {
        Check();
        var manifestPath = Path.Combine(directory, "kernel-manifest.json");
        if (new FileInfo(manifestPath).Length is < 1 or > 1_048_576) throw new InvalidDataException("Existing manifest byte limit.");
        var bytes = File.ReadAllBytes(manifestPath);
        using var document = JsonDocument.Parse(bytes, new JsonDocumentOptions { MaxDepth = 16 });
        var root = document.RootElement;
        var sourceHash = Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(Path.Combine("src", "Sezika.Kernels", "TransformerKernels.cs"))));
        if (root.GetProperty("schemaVersion").GetInt32() != 1 || root.GetProperty("compiler").GetString() != "ILGPU" ||
            root.GetProperty("sourceSha256").GetString() != sourceHash || root.GetProperty("compilerVersion").GetString() != "1.5.3" ||
            root.GetProperty("target").GetString() != "sm_70" || root.GetProperty("ptxVersion").GetString() != "7.0" || root.GetProperty("kernels").GetArrayLength() != 17)
            throw new InvalidDataException("Existing source/compiler/target/count identity differs.");
        string[] expected = ["VectorAdd", "Linear", "Embedding", "Norm", "SplitQkv", "Rope", "AttentionScores", "Softmax", "AttentionContext", "Add", "Activate", "GatedGelu", "RowBias", "TypeEmbeddingAdd", "MarkerCrossEntropy", "MarkerGradientSgd", "MarkerUpdateStatus"];
        var generated = new StringBuilder("// Generated by Sezika.KernelCompiler; do not edit.\nnamespace Sezika.Cuda;\n\ninternal static class GeneratedKernelArtifacts\n{\n    internal readonly record struct Descriptor(string Entry, int ParameterCount, int BlockSize);\n    internal const string CompilerVersion = \"ILGPU 1.5.3\";\n    internal const string SourceSha256 = \"");
        generated.Append(sourceHash).Append("\";\n");
        var index = 0;
        foreach (var item in root.GetProperty("kernels").EnumerateArray())
        {
            Check(); var name = item.GetProperty("name").GetString()!;
            if (index >= 17 || name != expected[index++] || item.GetProperty("ptx").GetString() != name + ".ptx" || item.GetProperty("entry").GetString() != "Kernel_" + name || item.GetProperty("blockSize").GetInt32() != 256)
                throw new InvalidDataException("Existing kernel order/path/entry/block differs.");
            var path = Path.Combine(directory, name + ".ptx");
            if (new FileInfo(path).Length is < 1 or > 1_048_576) throw new InvalidDataException("Existing PTX byte limit.");
            var ptx = File.ReadAllBytes(path);
            if (ptx[^1] != 0 || Convert.ToHexString(SHA256.HashData(ptx)) != item.GetProperty("sha256").GetString()) throw new InvalidDataException("Existing PTX SHA or terminator differs.");
            var ptxText = Encoding.ASCII.GetString(ptx);
            var entries = Regex.Matches(ptxText, @"\.entry\s+(?<name>[A-Za-z0-9_]+)\s*\(", RegexOptions.CultureInvariant, TimeSpan.FromSeconds(1));
            if (entries.Count != 1 || entries[0].Groups["name"].Value != item.GetProperty("entry").GetString())
                throw new InvalidDataException("Existing PTX must contain exactly its manifest entry.");
            var abi = ParseAbi(ptxText, typeof(TransformerKernels).GetMethod(name, BindingFlags.Public | BindingFlags.Static)!, Check);
            if (abi.Length != item.GetProperty("parameters").GetArrayLength()) throw new InvalidDataException("Existing parameter count differs.");
            for (var parameterIndex = 0; parameterIndex < abi.Length && parameterIndex < 16; parameterIndex++)
            {
                Check(); var saved = item.GetProperty("parameters")[parameterIndex]; var actual = abi[parameterIndex];
                if (saved.GetProperty("name").GetString() != actual.Name || saved.GetProperty("kind").GetString() != actual.Kind ||
                    saved.GetProperty("width").GetInt32() != actual.Width || saved.GetProperty("alignment").GetInt32() != actual.Alignment)
                    throw new InvalidDataException("Existing parameter ABI differs from C# and PTX.");
            }
            generated.Append("    internal static ReadOnlySpan<byte> ").Append(name).Append(" => new byte[] { ");
            for (var offset = 0; offset < ptx.Length && offset < 1_048_576; offset++) { if ((offset & 255) == 0) Check(); generated.Append("0x").Append(ptx[offset].ToString("X2")).Append(", "); }
            generated.Append("};\n    internal static Descriptor ").Append(name).Append("Descriptor => new(\"Kernel_").Append(name).Append("\", ").Append(abi.Length).Append(", 256);\n");
            Console.WriteLine($"Verified existing kernel {index}/17: {name}");
        }
        Check(); generated.Append("    internal const string ManifestSha256 = \"").Append(Convert.ToHexString(SHA256.HashData(bytes))).Append("\";\n}\n");
        File.WriteAllText(Path.Combine(directory, "GeneratedKernelArtifacts.g.cs"), generated.ToString(), new UTF8Encoding(false));
    }
    finally { Console.CancelKeyPress -= handler; }
}

static KernelParameter[] ParseAbi(string ptx, MethodInfo method, Action check)
{
    var lines = ptx.Split('\n');
    if (lines.Length > 65_536) throw new InvalidDataException("PTX ABI line count limit exceeded.");
    var values = new List<(string Type, int Width, int Alignment)>();
    foreach (var line in lines)
    {
        check();
        var match = Regex.Match(line.Trim(), @"^\.param(?: \.align (?<align>\d+))? \.(?:b|f)(?<bits>8|32|64)(?: (?<name>[A-Za-z0-9_]+)\[(?<array>\d+)\])?");
        if (!match.Success) continue;
        var bits = int.Parse(match.Groups["bits"].Value, CultureInfo.InvariantCulture);
        var width = match.Groups["array"].Success ? int.Parse(match.Groups["array"].Value, CultureInfo.InvariantCulture) : bits / 8;
        var alignment = match.Groups["align"].Success ? int.Parse(match.Groups["align"].Value, CultureInfo.InvariantCulture) : Math.Min(width, 4);
        values.Add((match.Groups["array"].Success ? "device_view" : bits == 32 ? "scalar32" : "scalar64", width, alignment));
    }
    var parameters = method.GetParameters();
    if (parameters.Length > 16) throw new InvalidDataException("Kernel parameter count limit exceeded.");
    if (values.Count != parameters.Length) throw new InvalidOperationException($"ABI count mismatch for {method.Name}: PTX={values.Count}, C#={parameters.Length}.\n{ptx}");
    var result = new KernelParameter[parameters.Length];
    for (var i = 0; i < parameters.Length; i++)
    {
        check();
        var expected = parameters[i].ParameterType.IsGenericType && parameters[i].ParameterType.GetGenericTypeDefinition() == typeof(ArrayView<>) ? ("device_view", 16, 8) : parameters[i].ParameterType == typeof(float) ? ("scalar32", 4, 4) : ("scalar32", 4, 4);
        if (values[i] != expected) throw new InvalidOperationException($"ABI mismatch for {method.Name} parameter {parameters[i].Name}: got {values[i]}, expected {expected}.");
        result[i] = new KernelParameter(parameters[i].Name!, expected.Item1, expected.Item2, expected.Item3);
    }
    return result;
}

public sealed record KernelParameter(string Name, string Kind, int Width, int Alignment);
public sealed record KernelRecord(string Name, string Entry, string Ptx, string Sha256, int BlockSize, KernelParameter[] Parameters);
